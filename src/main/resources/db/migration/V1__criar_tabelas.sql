-- MoveSaúde: estrutura inicial. Compatível com PostgreSQL (produção) e H2 no modo PostgreSQL (testes).

CREATE TABLE plano_convenio (
    id                        VARCHAR(40)   PRIMARY KEY,
    operadora                 VARCHAR(80)   NOT NULL,
    nome                      VARCHAR(80)   NOT NULL,
    creditos_mensais          INTEGER       NOT NULL,
    coparticipacao_por_trecho NUMERIC(10,2) NOT NULL,
    desconto_pct              NUMERIC(4,2)  NOT NULL,
    modalidades_cobertas      VARCHAR(60)   NOT NULL,
    finalidades_elegiveis     VARCHAR(200)  NOT NULL,
    autorizacao_para          VARCHAR(60)   NOT NULL
);

CREATE TABLE prestador (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_fantasia       VARCHAR(120)     NOT NULL,
    cnpj                VARCHAR(18)      NOT NULL UNIQUE,
    cidade              VARCHAR(80)      NOT NULL,
    modalidades         VARCHAR(60)      NOT NULL,
    status_verificacao  VARCHAR(20)      NOT NULL,
    pausado             BOOLEAN          NOT NULL DEFAULT FALSE,
    possui_tecnico      BOOLEAN          NOT NULL DEFAULT FALSE,
    possui_enfermeiro   BOOLEAN          NOT NULL DEFAULT FALSE,
    hora_inicio         TIME             NOT NULL,
    hora_fim            TIME             NOT NULL,
    taxa_oxigenio       NUMERIC(10,2)    NOT NULL DEFAULT 0,
    taxa_tecnico        NUMERIC(10,2)    NOT NULL DEFAULT 0,
    taxa_enfermeiro     NUMERIC(10,2)    NOT NULL DEFAULT 0,
    avaliacao           DOUBLE PRECISION NOT NULL DEFAULT 5,
    corridas_concluidas INTEGER          NOT NULL DEFAULT 0
);

CREATE TABLE prestador_tarifa (
    prestador_id BIGINT        NOT NULL REFERENCES prestador (id) ON DELETE CASCADE,
    modalidade   VARCHAR(20)   NOT NULL,
    base         NUMERIC(10,2) NOT NULL,
    por_km       NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (prestador_id, modalidade)
);

CREATE TABLE veiculo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prestador_id  BIGINT      NOT NULL REFERENCES prestador (id) ON DELETE CASCADE,
    tipo          VARCHAR(20) NOT NULL,
    modelo        VARCHAR(80) NOT NULL,
    placa         VARCHAR(10) NOT NULL UNIQUE,
    assentos      INTEGER     NOT NULL,
    vagas_cadeira INTEGER     NOT NULL DEFAULT 0,
    maca          BOOLEAN     NOT NULL DEFAULT FALSE,
    oxigenio      BOOLEAN     NOT NULL DEFAULT FALSE,
    combustivel   VARCHAR(20) NOT NULL
);

CREATE TABLE passageiro (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(120) NOT NULL,
    mobilidade    VARCHAR(30)  NOT NULL,
    acompanhantes INTEGER      NOT NULL DEFAULT 0,
    oxigenio      VARCHAR(20)  NOT NULL DEFAULT 'NAO',
    equipe        VARCHAR(20)  NOT NULL DEFAULT 'NAO',
    obesidade     BOOLEAN      NOT NULL DEFAULT FALSE,
    cao_guia      BOOLEAN      NOT NULL DEFAULT FALSE,
    plano_id      VARCHAR(40)  REFERENCES plano_convenio (id),
    carteirinha   VARCHAR(30)
);

CREATE TABLE corrida (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passageiro_id       BIGINT                   NOT NULL REFERENCES passageiro (id),
    origem              VARCHAR(200)             NOT NULL,
    destino             VARCHAR(200)             NOT NULL,
    distancia_km        DOUBLE PRECISION         NOT NULL,
    data_corrida        DATE                     NOT NULL,
    hora_embarque       TIME                     NOT NULL,
    ida_e_volta         BOOLEAN                  NOT NULL DEFAULT FALSE,
    finalidade          VARCHAR(20)              NOT NULL,
    modalidade_indicada VARCHAR(20)              NOT NULL,
    status              VARCHAR(20)              NOT NULL,
    prestador_id        BIGINT                   REFERENCES prestador (id),
    veiculo_id          BIGINT                   REFERENCES veiculo (id),
    modalidade_atendida VARCHAR(20),
    horario_confirmado  TIME,
    preco               NUMERIC(10,2),
    cliente_paga        NUMERIC(10,2),
    convenio_paga       NUMERIC(10,2),
    trechos_cobertos    INTEGER                  NOT NULL DEFAULT 0,
    comissao            NUMERIC(10,2),
    resumo_cobertura    VARCHAR(200),
    criada_em           TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizada_em       TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_veiculo_prestador ON veiculo (prestador_id);
CREATE INDEX idx_passageiro_plano ON passageiro (plano_id);
CREATE INDEX idx_corrida_passageiro_data ON corrida (passageiro_id, data_corrida);
CREATE INDEX idx_corrida_prestador ON corrida (prestador_id);
CREATE INDEX idx_corrida_veiculo ON corrida (veiculo_id);
CREATE INDEX idx_corrida_status ON corrida (status);
